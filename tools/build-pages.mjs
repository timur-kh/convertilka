function webAppLd(url, name, description) {
  return {
    '@context': 'https://schema.org',
    '@type': 'WebApplication',
    name,
    url,
    description,
    applicationCategory: 'MultimediaApplication',
    operatingSystem: 'Любая (работает в браузере)',
    inLanguage: 'ru',
    isAccessibleForFree: true,
    featureList: FEATURES,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'RUB' },
  };
}

/**
 * Относительные ссылки главной (assets/…, privacy.html, ./) → на нужное число уровней выше
 * для страниц в подпапках (/heic-to-jpg/ — 1 уровень, /formats/png/ — 2).
 * Ссылки, уже начинающиеся с ../ (в текстах), не трогаются.
 */
function rebase(html, depth = 1) {
  const up = '../'.repeat(depth);
  return html.replace(/(\s(?:href|src)=")(?!https?:|\/\/|#|\.\.\/|data:|mailto:|\/)([^"]*)"/g, (m, attr, path) =>
    `${attr}${path === './' ? up : up + path}"`);
}

function buildPage(template, p) {
  const url = `${SITE_URL}/${p.slug}/`;
  const faq = [...(p.faq || []), ...GENERAL_FAQ];
  let html = template;

  html = slot(html, 'meta', `
  <title>${esc(p.title)}</title>
  <meta name="description" content="${esc(withPrivacy(p.description))}">
  <link rel="canonical" href="${url}">
  <meta name="theme-color" content="#4f46e5">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${SITE_NAME}">
  <meta property="og:url" content="${url}">
  <meta property="og:title" content="${esc(p.title)}">
  <meta property="og:description" content="${esc(withPrivacy(p.description))}">
  `);
  // theme-color уже есть в meta-блоке — убираем дубль из шаблона
  html = html.replace(/\n  <meta name="theme-color" content="#4f46e5">(?=\n  <meta property="og:type")/, '');

  html = slot(html, 'ld', '\n  ' + [
    jsonLd(webAppLd(url, p.h1, withPrivacy(p.description))),
    jsonLd({
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: SITE_NAME, item: `${SITE_URL}/` },
        { '@type': 'ListItem', position: 2, name: p.label, item: url },
      ],
    }),
    jsonLd({
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: faq.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })),
    }),
  ].join('\n  ') + '\n  ');

  html = slot(html, 'hero', `
      <nav class="breadcrumbs" aria-label="Навигация"><a href="./">${SITE_NAME}</a> › ${esc(p.label)}</nav>
      <h1>${esc(p.h1)}</h1>
      <p class="lead">${esc(p.lead)}</p>
      `);
  html = slot(html, 'drop', `<p class="drop-title">${p.drop}</p>`);
  html = slot(html, 'content', `
    <section class="container section">
      <article class="pair-article">${p.body}
      </article>
    </section>
    `);
  html = slot(html, 'popular', popularBlock(p.slug, './'));
  html = slot(html, 'faq', faqHtml(faq));
  // Настройки страницы для app.js: формат по умолчанию, особый инструмент, качество и размер картинок
  const data = { from: p.from, to: p.to, tool: p.tool, quality: p.quality, 'max-side': p.maxSide };
  const attrs = Object.entries(data).filter(([, v]) => v).map(([k, v]) => `data-${k}="${esc(v)}"`).join(' ');
  html = html.replace('<body>', `<body ${attrs}>`);
  html = html.replace('<!doctype html>', `<!doctype html>\n${MARK}`);
  // Ссылки на другие страницы пар внутри текстов написаны как ../slug/ — их rebase не трогает
  return rebase(html);
}

