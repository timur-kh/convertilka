/** Заменяет содержимое между <!--seo:name--> и <!--/seo:name-->. */
function slot(html, name, content) {
  const re = new RegExp(`<!--seo:${name}-->[\\s\\S]*?<!--/seo:${name}-->`);
  if (!re.test(html)) throw new Error(`В шаблоне нет метки seo:${name}`);
  return html.replace(re, `<!--seo:${name}-->${content}<!--/seo:${name}-->`);
}

function validate() {
  const slugs = new Set();
  for (const p of PAGES) {
    for (const k of ['slug', 'from', 'to', 'label', 'title', 'description', 'h1', 'lead', 'drop', 'body']) {
      if (!p[k]) throw new Error(`${p.slug || '?'}: нет поля ${k}`);
    }
    if (!/^[a-z0-9-]+$/.test(p.slug)) throw new Error(`${p.slug}: в адресе только латиница, цифры и дефис`);
    if (!TABS.some(([id]) => id === p.cat)) throw new Error(`${p.slug}: неизвестная категория cat «${p.cat}»`);
    if (slugs.has(p.slug)) throw new Error(`${p.slug}: повторяется`);
    slugs.add(p.slug);
    if (p.title.length > 70) console.warn(`  ! ${p.slug}: title длиннее 70 символов (${p.title.length}) — поисковик обрежет`);
    if (p.description.length > 170) console.warn(`  ! ${p.slug}: description длиннее 170 символов (${p.description.length})`);
  }
}

