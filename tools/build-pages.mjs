  html = slot(html, 'faq', faqHtml(faq));
  // В статьях не нужны общие блоки «Что умеет конвертировать» и «Частые вопросы»
  html = html.replace(/\n\s*<section id="formats"[\s\S]*?<\/section>/, '').replace(/\n\s*<section id="faq"[\s\S]*?<\/section>/, '');
  html = html.replace('<a href="#faq">', '<a href="./#faq">'); // «Вопросы» в шапке — на главную
