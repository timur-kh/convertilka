/**
 * Блок ссылок на все конвертации (перелинковка) с вкладками по категориям.
 * Все ссылки есть в HTML (их видят поисковики); вкладки включает app.js, без JS видно всё.
 */
function popularBlock(current, prefix) {
  const link = (p) => `<a href="${prefix}${p.slug}/"${p.slug === current ? ' aria-current="page"' : ''}>${esc(p.label)}</a>`;
  const panels = TABS.map(([id, label]) => {
    const list = PAGES.filter((p) => (id === 'top' ? p.top : p.cat === id));
    if (!list.length) return '';
    return `
      <div class="links-panel" id="links-${id}" data-panel="${id}" role="tabpanel" aria-label="${label}">
        <nav class="links-grid" aria-label="${label}">
          ${list.map(link).join('\n          ')}
        </nav>
      </div>`;
  }).join('');
  return `
    <section class="container section popular" data-later aria-labelledby="popular-title">
      <h2 id="popular-title">Популярные конвертации и инструменты</h2>
      <div class="links-tabs" role="tablist" aria-label="Категории" hidden>
        ${TABS.map(([id, label], i) => `<button type="button" role="tab" class="links-tab" data-tab="${id}" aria-controls="links-${id}" aria-selected="${i === 0}">${label}</button>`).join('\n        ')}
      </div>${panels}
    </section>
    `;
}

